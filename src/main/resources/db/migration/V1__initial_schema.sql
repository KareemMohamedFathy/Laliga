-- Table: public.teams

-- DROP TABLE IF EXISTS public.teams;

CREATE TABLE public.teams
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(255)  NOT NULL,
    CONSTRAINT unique_name UNIQUE (name)
    );
-- Table: public.matches

-- DROP TABLE IF EXISTS public.matches;

CREATE TABLE  public.matches
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    away_corners integer,
    away_fouls integer,
    away_goals integer,
    away_red_cards integer,
    away_shots integer,
    away_shots_on_target integer,
    away_yellow_cards integer,
    half_time_away_goals integer,
    half_time_home_goals integer,
    half_time_result character varying(255) ,
    home_corners integer,
    home_fouls integer,
    home_goals integer,
    home_red_cards integer,
    home_shots integer,
    home_shots_on_target integer,
    home_yellow_cards integer,
    match_date date,
    match_time time(0) without time zone,
    result character varying(255) ,
    away_team_id bigint,
    home_team_id bigint,
    CONSTRAINT away_foreign_team_id FOREIGN KEY (away_team_id)
    REFERENCES public.teams (id) MATCH SIMPLE
                       ON UPDATE NO ACTION
                       ON DELETE NO ACTION,
    CONSTRAINT home_foreign_team_id FOREIGN KEY (home_team_id)
    REFERENCES public.teams (id) MATCH SIMPLE
                       ON UPDATE NO ACTION
                       ON DELETE NO ACTION
    );


